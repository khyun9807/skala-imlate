-- =====================================================================
-- V2 — 등록 취소 기능 (취소 비밀번호 + 소프트 삭제)
--
--   운영 요청: "등록된 것을 취소하는 것도 가능하게. 남이 다른 사람의 등록을 취소할 수 있으니
--              등록할 때 비밀번호 숫자 4자리도 받아서 보관하고, 취소할 때 반·이름·호수 +
--              그 비밀번호가 모두 맞았을 때만 취소되게."
--
--   이 마이그레이션은 **실서비스 운영 중인 DB 위에서 실행된다**. 그래서 두 컬럼 모두 NULL 허용이다.
--   NOT NULL 로 두면 이미 들어 있는 기존 등록 행 때문에 마이그레이션이 통째로 실패하고,
--   `ddl-auto: validate` 환경에서는 앱이 아예 뜨지 못한다.
--   "비밀번호 필수"는 API 검증(@NotBlank + @Pattern)에서 강제하고, 스키마는 관대하게 둔다.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1) 취소 비밀번호 해시
--
--   평문 4자리를 그대로 두면 DB 를 보는 사람이 누구든 남의 등록을 취소할 수 있다.
--   저장 형식은 자기 서술적(self-describing)이라 나중에 파라미터를 올려도 기존 행을 읽을 수 있다:
--       pbkdf2-sha256$<반복횟수>$<base64(salt)>$<base64(hash)>
--   4자리는 경우의 수가 1만개뿐이라 해시만으로는 오프라인 대입에 무력하다.
--   그래서 앱이 서버 시크릿에서 유도한 pepper 를 섞는다(CancelPasswordHasher 참고).
--   길이 200 은 위 형식의 최대 길이(대략 130자)에 여유를 둔 값이다.
-- ---------------------------------------------------------------------
ALTER TABLE return_registration
    ADD COLUMN cancel_password_hash VARCHAR(200) NULL COMMENT '취소 비밀번호 해시(PBKDF2, pepper 포함)';

-- ---------------------------------------------------------------------
-- 2) 취소 시각 (소프트 삭제)
--
--   **왜 행을 지우지 않는가 — 이게 이 마이그레이션에서 가장 중요한 결정이다.**
--   행을 DELETE 하면 Redis WAL 에는 그 사람의 등록 기록이 그대로 남는다.
--   그 상태로 21:50 대사(ReconciliationService)가 돌면 "WAL 에는 있는데 DB 에 없다"고 판단해
--   **취소한 등록을 되살려 사감 명단에 다시 올린다.** 취소가 조용히 무효가 되는 것이다.
--   시각을 남겨 두면 행이 계속 존재하므로 대사가 되살리지 않고,
--   "언제 취소했는가"라는 근거도 남는다(교육생이 취소했다고 주장할 때 확인 가능).
--
--   되살아나기와 별개로, 명단·통계 조회는 모두 `cancelled_at IS NULL` 로 걸러야 한다.
-- ---------------------------------------------------------------------
ALTER TABLE return_registration
    ADD COLUMN cancelled_at DATETIME(6) NULL COMMENT '취소 시각(KST). NULL 이면 유효한 등록';

-- ---------------------------------------------------------------------
-- 3) 명단 조회 인덱스
--
--   사감 발송·조회 페이지는 항상 "그날의 취소되지 않은 등록"을 읽는다.
--   기존 idx_return_registration_date 는 날짜만 타므로 취소분까지 읽고 나서 걸러낸다.
--   (registration_date, cancelled_at) 복합 인덱스로 취소분을 인덱스 단계에서 떨군다.
-- ---------------------------------------------------------------------
CREATE INDEX idx_return_registration_date_active
    ON return_registration (registration_date, cancelled_at);
